const {
  renderLoginTemplate,
  renderPasswordChangeTemplate,
  renderSignupTemplate
} = require('./authTemplates');
const { renderProfileUpdateTemplate } = require('./accountTemplates');
const { renderOrderPlacedTemplate } = require('./commerceTemplates');
const { renderCustomActivityTemplate } = require('./customTemplate');

const TEMPLATE_MAP = {
  // Authentication & Security
  login: renderLoginTemplate,
  signin: renderLoginTemplate,
  'new-login': renderLoginTemplate,
  password_change: renderPasswordChangeTemplate,
  'password-reset': renderPasswordChangeTemplate,
  signup: renderSignupTemplate,
  register: renderSignupTemplate,
  welcome: renderSignupTemplate,

  // Account & Profile
  profile_update: renderProfileUpdateTemplate,
  'profile-edit': renderProfileUpdateTemplate,

  // Commerce & Billing
  order_placed: renderOrderPlacedTemplate,
  purchase: renderOrderPlacedTemplate,

  // Fallback
  custom: renderCustomActivityTemplate
};

/**
 * Resolves and renders the email subject, HTML, and text
 */
function resolveAndRenderEmail(payload) {
  const activityType = (payload.activity?.type || 'custom').toLowerCase().trim();
  const renderer = TEMPLATE_MAP[activityType] || renderCustomActivityTemplate;

  const rendered = renderer(payload);

  // Allow custom subject override if caller explicitly specified one
  if (payload.activity?.subject) {
    rendered.subject = payload.activity.subject;
  }

  return {
    activityType,
    subject: rendered.subject,
    html: rendered.html,
    text: rendered.text
  };
}

